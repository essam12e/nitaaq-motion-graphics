/**
 * earshot bridge (node). earshot (MIT, github.com/Leonxlnx/earshot) ships a bank
 * of 252 sound effects stored as code that render by id with pure DSP: no
 * models, no network, no recorded audio. `earshot sfx` aims a take at a moment
 * (dur / apex / pitch knobs, measured onset / peak / end, a model-free audit).
 *
 * NITAAQ runs it through tools/earshot_render.py in ONE python process per
 * batch, and keeps every take in the shared sound library
 * (workspace/.sound/library/earshot), keyed by id + seed + knobs: the same
 * moment in another film reuses the file.
 *
 * Python: NITAAQ_EARSHOT_PYTHON, else <repo>/.venv-sound/bin/python
 * (`npm run sound:setup` makes it: numpy, scipy, soundfile, soxr + earshot at a
 * pinned commit, without torch: the bank needs none of the model packages).
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { ROOT } from '../workspace';
import { soundLibraryDir } from './library';

export const EARSHOT_COMMIT = '591fa3e028032e6dce56620a20e932e35667e8d8';

export interface EarshotJob {
  id: string;
  seed?: number;
  dur?: number;
  apex?: number;
  pitch?: string;
}
export interface EarshotTake {
  file: string;
  id: string;
  seed: number;
  onset_s: number;
  peak_s: number;
  end_s: number;
  dur_s: number;
  peak_db: number;
  lufs_m_max: number | null;
  clean: boolean;
  audit?: string;
  edits?: Record<string, string>;
  note?: string | null;
}

export function earshotPython(env: NodeJS.ProcessEnv = process.env): string | null {
  const cands = [env.NITAAQ_EARSHOT_PYTHON, join(ROOT, '.venv-sound', 'bin', 'python'), join(ROOT, '.venv-sound', 'Scripts', 'python.exe')].filter(Boolean) as string[];
  for (const p of cands) if (existsSync(p)) return p;
  return null;
}

let okCache: { py: string; ok: boolean; why: string } | null = null;
/** Is earshot importable (bank only)? Cached per process. */
export function earshotAvailable(): { ok: boolean; why: string } {
  if (process.env.NITAAQ_NO_EARSHOT === '1') return { ok: false, why: 'NITAAQ_NO_EARSHOT=1' };
  const py = earshotPython();
  if (!py) return { ok: false, why: 'no earshot python (run `npm run sound:setup`, or set NITAAQ_EARSHOT_PYTHON)' };
  if (okCache?.py === py) return okCache;
  const r = spawnSync(py, ['-I', join(ROOT, 'tools', 'earshot_render.py'), '--version'], { encoding: 'utf8', timeout: 120000 });
  okCache = { py, ok: r.status === 0, why: r.status === 0 ? `earshot ${r.stdout.trim()}` : `earshot import failed: ${(r.stderr || '').trim().split('\n').pop()}` };
  return okCache;
}

export const takeKey = (j: EarshotJob) => createHash('sha1').update(JSON.stringify([j.id, j.seed ?? null, j.dur ?? null, j.apex ?? null, j.pitch ?? null])).digest('hex').slice(0, 16);

/** Render (or reuse) takes. Returns one take per job, in order. */
export function renderTakes(jobs: EarshotJob[]): EarshotTake[] {
  const dir = join(soundLibraryDir(), 'earshot');
  mkdirSync(dir, { recursive: true });
  const out: (EarshotTake | null)[] = jobs.map((j) => {
    const k = takeKey(j);
    const meta = join(dir, `${k}.json`);
    const wav = join(dir, `${k}.wav`);
    if (existsSync(meta) && existsSync(wav)) return JSON.parse(readFileSync(meta, 'utf8')) as EarshotTake;
    return null;
  });
  const todo = jobs.map((j, i) => ({ j, i })).filter((x) => !out[x.i]);
  if (todo.length) {
    const av = earshotAvailable();
    if (!av.ok) throw new Error(av.why);
    const jobFile = join(dir, `.jobs-${process.pid}.json`);
    writeFileSync(jobFile, JSON.stringify(todo.map(({ j }) => ({ ...j, out: join(dir, `${takeKey(j)}.wav`) }))));
    const r = spawnSync(earshotPython()!, ['-I', join(ROOT, 'tools', 'earshot_render.py'), jobFile], { encoding: 'utf8', timeout: 20 * 60000, maxBuffer: 1 << 26 });
    if (r.status !== 0) throw new Error(`earshot render failed: ${(r.stderr || '').trim().split('\n').slice(-3).join(' ')}`);
    const res = JSON.parse(r.stdout.trim().split('\n').pop()!) as (Omit<EarshotTake, 'file'> & { out: string })[];
    res.forEach((t, n) => {
      const { j, i } = todo[n];
      const take: EarshotTake = { ...t, file: t.out, id: j.id };
      delete (take as unknown as { out?: string }).out;
      writeFileSync(join(dir, `${takeKey(j)}.json`), JSON.stringify({ ...take, job: j, license: 'generated by earshot (MIT code; no recorded audio)', source: `earshot@${EARSHOT_COMMIT.slice(0, 7)} bank` }, null, 1));
      out[i] = take;
    });
  }
  return out as EarshotTake[];
}

/** earshot's bank list (id, length, peak, kinds, knobs, native pitch), cached in the library folder. */
export function earshotBank(): { id: string; dur_s: number; peak_s: number; kinds?: string[]; knobs?: { pitch?: unknown } }[] {
  const file = join(soundLibraryDir(), 'earshot', 'bank.json');
  if (existsSync(file)) return JSON.parse(readFileSync(file, 'utf8'));
  const py = earshotPython();
  if (!py) return [];
  const r = spawnSync(py, ['-I', join(ROOT, 'tools', 'earshot_render.py'), '--list'], { encoding: 'utf8', timeout: 120000, maxBuffer: 1 << 26 });
  if (r.status !== 0) return [];
  mkdirSync(join(soundLibraryDir(), 'earshot'), { recursive: true });
  writeFileSync(file, r.stdout);
  return JSON.parse(r.stdout);
}
