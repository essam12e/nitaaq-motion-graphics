function pal(p: Partial<Palette> & Pick<Palette, 'background' | 'primary' | 'textPrimary'>): Palette {
  return {
    backgroundAlt: p.background,
    surface: p.background,
    surfaceAlt: p.background,
    secondary: p.primary,
    accent: p.primary,
    textSecondary: p.textPrimary,
    textOnPrimary: '#FFFFFF',
    textOnSurface: p.textPrimary,
    border: alpha(p.textPrimary, 0.14),
    glow: p.primary,
    positive: '#22C55E',
    negative: '#EF4444',
    ...p,
  };
}

