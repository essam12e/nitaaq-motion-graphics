export function findStyleId(id: string | undefined): string | undefined {
  if (!id) return undefined;
  const k = id.trim().toLowerCase().replace(/[\s_/]+/g, '-');
  if (STYLE_PRESETS[k]) return k;
  if (STYLE_ALIASES[k]) return STYLE_ALIASES[k];
  return undefined;
}
